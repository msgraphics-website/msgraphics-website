// Writes the shop theme's menu (Services and Digital dropdowns) from the website's
// services list, so both sites show the same navigation.
// Run: node scripts/make-wp-menu.mjs  (then re-zip wordpress-theme/msgraphics-shop)
import fs from 'node:fs';
const raw = JSON.parse(fs.readFileSync('src/data/content/services.json', 'utf8'));
const all = raw.services || raw;
const hub = 'website-app-digital-marketing';
const esc = (t) => t.replace(/'/g, "\\'");
const line = (s) => `    array( '${esc(s.title)}', '/services/${s.slug}/', '${s.icon}', '${esc(s.shortTitle)}' ),`;
const out = `<?php
// Generated by scripts/make-wp-menu.mjs from the website's services list. Do not edit by hand.
// Each row: title, path on the main website, icon, short title.
return array(
  'services' => array(
${all.filter((s) => !s.parent).map(line).join('\n')}
  ),
  'digital_hub' => '/services/${hub}/',
  'digital' => array(
${all.filter((s) => s.parent === hub).map(line).join('\n')}
  ),
);
`;
fs.writeFileSync('wordpress-theme/msgraphics-shop/inc/menu-data.php', out);
// Icons used by the menu, added to the theme's icon set.
const iconsFile = 'wordpress-theme/msgraphics-shop/inc/icons.php';
let icons = fs.readFileSync(iconsFile, 'utf8');
let add = '';
for (const name of new Set(all.map((s) => s.icon).concat(['chevron-down', 'arrow-right', 'monitor-smartphone']))) {
  if (icons.includes(`'${name}' =>`)) continue;
  const svg = fs.readFileSync(`node_modules/lucide-static/icons/${name}.svg`, 'utf8').replace(/<!--.*?-->/s, '');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s+/g, ' ').trim();
  add += `  '${name}' => '${inner.replace(/'/g, "\\'")}',\n`;
}
if (add) fs.writeFileSync(iconsFile, icons.replace("  'whatsapp' => 'WA',", add + "  'whatsapp' => 'WA',"));
console.log('menu-data.php written');
